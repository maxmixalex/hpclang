static void gallery_chrome_char(struct hpclang_surface *surface, int32_t x, int32_t y,
                                unsigned char c)
{
    if (c >= 'a' && c <= 'z')
        c = (unsigned char)(c - ('a' - 'A'));
    if (c < 0x20u || c > 0x5fu)
        c = '?';
    const uint8_t *rows = gallery_chrome_rows[c - 0x20u];
    for (int32_t yy = 0; yy < 6; ++yy) {
        uint8_t row = rows[yy];
        for (int32_t xx = 0; xx < 4; ++xx) {
            if ((row & (uint8_t)(1u << (3 - xx))) != 0u)
                hpclang_surface_set_pixel(surface, x + xx, y + yy, 255u);
        }
    }
}

static void gallery_chrome_text(struct hpclang_surface *surface, int32_t x, int32_t y,
                                int32_t right, const char *text)
{
    for (const unsigned char *p = (const unsigned char *)text; *p != 0u && x + 4 <= right; ++p) {
        gallery_chrome_char(surface, x, y, *p);
        x += 5;
    }
}

static void gallery_chrome_status_centered(struct hpclang_surface *surface, int32_t y,
                                           const char *text)
{
    size_t n = strlen(text);
    int32_t width = n != 0u ? (int32_t)(n * 5u - 1u) : 0;
    int32_t x = (GALLERY_LCD_WIDTH - width) / 2;
    if (x < 0)
        x = 0;
    gallery_chrome_text(surface, x, y, GALLERY_LCD_WIDTH - 1, text);
}

