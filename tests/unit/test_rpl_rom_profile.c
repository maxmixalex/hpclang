struct input
{
    uint32_t size, next, calls, fail;
    int error;
};
static int read_pattern(void *context, uint32_t offset, uint8_t *data, uint32_t bytes)
{
    struct input *input = context;
    assert(offset == input->next && offset <= input->size && bytes <= input->size - offset &&
           bytes <= 64);
    if (++input->calls == input->fail)
        return input->error;
    for (uint32_t i = 0; i < bytes; ++i)
        data[i] = (uint8_t)((offset + i) * 13u + 7u);
    input->next += bytes;
    return 0;
}
