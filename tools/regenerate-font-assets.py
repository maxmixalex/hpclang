#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from pathlib import Path


def load_font_tool():
    path = Path(__file__).with_name("hpclang-font.py")
    spec = importlib.util.spec_from_file_location("hpclang_font_tool", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


hf = load_font_tool()

SPECIAL_IDS = {
    "newrpl/bitmap-masters/Font6_mediumA.bmp": "newrpl_6a",
    "newrpl/bitmap-masters/Font8_StyleC.bmp": "newrpl_8c",
    "newrpl/bitmap-masters/Font10_StyleA.bmp": "newrpl_10a",
}


def cmake_quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace(";", "\\;")


def face_id(row: dict, used: dict[str, str]) -> str:
    selector = row["selector"]
    if selector in SPECIAL_IDS:
        ident = SPECIAL_IDS[selector]
    else:
        family = str(row.get("family") or Path(row["path"]).parent.name or "font")
        stem = Path(row["path"]).stem
        face = str(row.get("face") or "")
        raw = "_".join(part for part in (family, stem, face) if part)
        ident = hf.c_ident(raw).lower().strip("_") or "font"
        if ident[0].isdigit():
            ident = "font_" + ident
    owner = used.get(ident)
    if owner is not None and owner != selector:
        ident += "_" + hashlib.sha256(selector.encode("utf-8")).hexdigest()[:8]
    used[ident] = selector
    return ident


def asm_bytes(data: bytes) -> str:
    if not data:
        return "0"
    return ",".join(str(value) for value in data)


def emit_glyph_source(font, ident: str, glyphs: list, out) -> None:
    symbol = f"hpclang_font_{ident}"
    print(".syntax unified", file=out)
    print("", file=out)
    print(".macro G cp,xo,yo,w,h,a,s,bytes:vararg", file=out)
    print(f'.section .rodata.hpclang.font.{ident}.cp\\cp\\().bitmap,"a",%progbits', file=out)
    print(f".global {symbol}_cp\\cp\\()_bitmap", file=out)
    print(f"{symbol}_cp\\cp\\()_bitmap:", file=out)
    print(".byte \\bytes", file=out)
    print(f'.section .rodata.hpclang.font.{ident}.cp\\cp\\().glyph,"a",%progbits', file=out)
    print(".balign 4", file=out)
    print(f".global {symbol}_cp\\cp", file=out)
    print(f"{symbol}_cp\\cp:", file=out)
    print(".word \\cp", file=out)
    print(f".word {symbol}_cp\\cp\\()_bitmap", file=out)
    print(".hword \\xo,\\yo,\\w,\\h,\\a,\\s", file=out)
    print(".endm", file=out)
    print("", file=out)
    for glyph in glyphs:
        print(
            "G "
            f"{glyph.codepoint},{glyph.x_offset},{glyph.y_offset},"
            f"{glyph.width},{glyph.height},{glyph.advance},{glyph.stride},"
            f"{asm_bytes(glyph.bitmap)}",
            file=out,
        )
    print("", file=out)
    print(".purgem G", file=out)


def emit_full_descriptor(font, ident: str, out) -> None:
    symbol = f"hpclang_font_{ident}"
    glyphs = sorted(font.glyphs.values(), key=lambda glyph: glyph.codepoint)
    fallback = 0x3F if 0x3F in font.glyphs else (glyphs[0].codepoint if glyphs else 0xFFFFFFFF)
    print(".syntax unified", file=out)
    print("", file=out)
    print(f'.section .rodata.hpclang.font.{ident}.full.map,"a",%progbits', file=out)
    print(".balign 4", file=out)
    print(f".global {symbol}_full_glyphs", file=out)
    print(f"{symbol}_full_glyphs:", file=out)
    for glyph in glyphs:
        print(f".word {symbol}_cp{glyph.codepoint}", file=out)
    print("", file=out)
    print(f'.section .rodata.hpclang.font.{ident}.full.data,"a",%progbits', file=out)
    print(".balign 4", file=out)
    print(f".global {symbol}_full_data", file=out)
    print(f"{symbol}_full_data:", file=out)
    print(f".word {symbol}_full_glyphs", file=out)
    print(f".word {len(glyphs)}", file=out)
    print(f".word {fallback}", file=out)
    print(
        f".hword {font.ascent},{font.descent},{font.line_height},{font.nominal_advance}",
        file=out,
    )
    print("", file=out)
    print(f'.section .rodata.hpclang.font.{ident}.full.font,"a",%progbits', file=out)
    print(".balign 4", file=out)
    print(f".global {symbol}_full", file=out)
    print(f"{symbol}_full:", file=out)
    print(".word 1,1", file=out)
    print(f".word {symbol}_full_data", file=out)


def write_codepoints(path: Path, ident: str, codepoints: list[int]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as out:
        print("# Generated by tools/regenerate-font-assets.py. Do not edit by hand.", file=out)
        print(f"set(HPCLANG_FONT_{ident}_CODEPOINTS", file=out)
        for cp in codepoints:
            print(f"    {cp}", file=out)
        print(")", file=out)


def generate_face(font, ident: str, out_dir: Path, chunk_glyphs: int) -> list[str]:
    glyphs = sorted(font.glyphs.values(), key=lambda glyph: glyph.codepoint)
    sources: list[str] = []
    if len(glyphs) <= chunk_glyphs:
        name = f"{ident}.S"
        path = out_dir / name
        with path.open("w", encoding="utf-8", newline="\n") as out:
            emit_glyph_source(font, ident, glyphs, out)
            print("", file=out)
            emit_full_descriptor(font, ident, out)
        sources.append(name)
        return sources

    for index in range(0, len(glyphs), chunk_glyphs):
        chunk = glyphs[index : index + chunk_glyphs]
        number = index // chunk_glyphs
        name = f"{ident}_{number:04d}.S"
        with (out_dir / name).open("w", encoding="utf-8", newline="\n") as out:
            emit_glyph_source(font, ident, chunk, out)
        sources.append(name)
    descriptor = f"{ident}_full.S"
    with (out_dir / descriptor).open("w", encoding="utf-8", newline="\n") as out:
        emit_full_descriptor(font, ident, out)
    sources.append(descriptor)
    return sources


def write_index(path: Path, records: list[dict]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as out:
        print("# Generated by tools/regenerate-font-assets.py. Do not edit by hand.", file=out)
        print("", file=out)
        print("set(HPCLANG_FONT_IDS", file=out)
        for record in records:
            print(f"    {record['id']}", file=out)
        print(")", file=out)
        print("", file=out)
        for record in records:
            ident = record["id"]
            print(f"set(HPCLANG_FONT_{ident}_SELECTOR \"{cmake_quote(record['selector'])}\")", file=out)
            print(f"set(HPCLANG_FONT_{ident}_SOURCES", file=out)
            for source in record["sources"]:
                print(f'    "${{CMAKE_CURRENT_LIST_DIR}}/{cmake_quote(source)}"', file=out)
            print(")", file=out)
            print(f"set(HPCLANG_FONT_{ident}_ASCENT {record['ascent']})", file=out)
            print(f"set(HPCLANG_FONT_{ident}_DESCENT {record['descent']})", file=out)
            print(f"set(HPCLANG_FONT_{ident}_LINE_HEIGHT {record['line_height']})", file=out)
            print(f"set(HPCLANG_FONT_{ident}_NOMINAL_ADVANCE {record['nominal_advance']})", file=out)
            print(
                f'set(HPCLANG_FONT_{ident}_CODEPOINTS_FILE "${{CMAKE_CURRENT_LIST_DIR}}/{ident}.codepoints.cmake")',
                file=out,
            )
            print("", file=out)


def clean_generated(out_dir: Path) -> None:
    if not out_dir.exists():
        return
    for path in out_dir.iterdir():
        if path.is_file() and (
            path.suffix == ".S"
            or path.name.endswith(".codepoints.cmake")
            or path.name in {"index.cmake", "catalog.json"}
        ):
            path.unlink()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Regenerate checked-in hpclang assembly font assets from runtime/fonts/fonts.zip."
    )
    parser.add_argument("--package", default="runtime/fonts/fonts.zip")
    parser.add_argument("--output-dir", default="runtime/fonts/generated")
    parser.add_argument("--chunk-glyphs", type=int, default=512)
    parser.add_argument("--selector", action="append", default=[], help="limit generation to exact selectors")
    parser.add_argument("--keep-stale", action="store_true", help="do not remove old generated assets first")
    args = parser.parse_args()

    if args.chunk_glyphs <= 0:
        parser.error("--chunk-glyphs must be positive")

    package = hf.Package(args.package)
    bad = package.verify()
    if bad:
        raise SystemExit("package verification failed:\n" + "\n".join(bad))

    rows = hf.catalog(package)
    if args.selector:
        wanted = set(args.selector)
        rows = [row for row in rows if row["selector"] in wanted]
        missing = sorted(wanted - {row["selector"] for row in rows})
        if missing:
            raise SystemExit("unknown selector(s): " + ", ".join(missing))

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    if not args.keep_stale:
        clean_generated(out_dir)

    used_ids: dict[str, str] = {}
    records: list[dict] = []
    total_glyphs = 0
    total_sources = 0

    for number, row in enumerate(rows, 1):
        selector = row["selector"]
        ident = face_id(row, used_ids)
        print(f"[{number}/{len(rows)}] {selector} -> {ident}", flush=True)
        font = hf.load_selected(package, selector, "FULL")
        if not font.glyphs:
            raise SystemExit(f"{selector}: no mapped glyphs")
        sources = generate_face(font, ident, out_dir, args.chunk_glyphs)
        codepoints = sorted(font.glyphs)
        write_codepoints(out_dir / f"{ident}.codepoints.cmake", ident, codepoints)
        record = {
            "id": ident,
            "selector": selector,
            "path": row["path"],
            "family": row.get("family"),
            "format": row.get("format"),
            "face": row.get("face"),
            "glyph_count": len(codepoints),
            "ascent": font.ascent,
            "descent": font.descent,
            "line_height": font.line_height,
            "nominal_advance": font.nominal_advance,
            "sources": sources,
        }
        records.append(record)
        total_glyphs += len(codepoints)
        total_sources += len(sources)

    records.sort(key=lambda record: record["id"])
    write_index(out_dir / "index.cmake", records)
    with (out_dir / "catalog.json").open("w", encoding="utf-8", newline="\n") as out:
        json.dump(
            {
                "package": str(args.package),
                "package_sha256": hashlib.sha256(Path(args.package).read_bytes()).hexdigest(),
                "faces": records,
            },
            out,
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        )
        out.write("\n")

    print(
        f"PASS: generated {len(records)} faces / {total_glyphs} glyph mappings / "
        f"{total_sources} assembly sources in {out_dir}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
